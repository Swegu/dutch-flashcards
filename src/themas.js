function parseThemaEntry(raw, gloss, posHint) {
  let s = String(raw || '').trim();
  let article = null;

  // Handle PDF typo "voorstel (he)t" -> "voorstel (het)"
  s = s.replace(/\(he\)t\b/i, '(het)');

  // Handle leading "de rit"
  const leadingArt = /^(de|het)\s+(.+)$/i.exec(s);
  if (leadingArt && !/\((?:de|het)/i.test(s)) {
    article = leadingArt[1].toLowerCase();
    s = leadingArt[2].trim();
  }

  // Handle trailing "(de)", "(het)", "(het, de)", "(de; -en)"
  const trailingArt = /\(\s*(het\s*,\s*de|de\s*,\s*het|de|het)(?:\s*;[^)]*)?\s*\)\s*$/i.exec(s);
  if (trailingArt) {
    const rawArt = trailingArt[1].toLowerCase().replace(/\s+/g, '');
    article = rawArt.includes(',') ? 'het, de' : rawArt;
    s = s.slice(0, trailingArt.index).trim();
  }

  const word = s.toLowerCase();
  const pos = posHint || (article ? 'noun' : null);

  return {
    word,
    article,
    glosses: [gloss],
    pos,
  };
}

function seedThemaWords(db) {
  const getWord = db.prepare('SELECT id, article, glosses, pos, themas, level FROM words WHERE word = ?');
  const insWord = db.prepare(`
    INSERT INTO words(word, pos, article, glosses, level, themas)
    VALUES(?, ?, ?, ?, ?, ?)
  `);
  const updWord = db.prepare(`
    UPDATE words
    SET article = ?,
        pos = ?,
        glosses = ?,
        themas = ?
    WHERE id = ?
  `);

  db.transaction(() => {
    for (const tInfo of THEMA_LIST) {
      const entries = THEMA_ENTRIES[tInfo.slug] || [];
      for (const [raw, gloss, posHint] of entries) {
        const parsed = parseThemaEntry(raw, gloss, posHint);
        const existing = getWord.get(parsed.word);
        if (existing) {
          let themas = [];
          try { themas = existing.themas ? JSON.parse(existing.themas) : []; } catch { themas = []; }
          if (!themas.includes(tInfo.slug)) themas.push(tInfo.slug);

          let existingGlosses = [];
          try { existingGlosses = existing.glosses ? JSON.parse(existing.glosses) : []; } catch { existingGlosses = []; }
          const nextGlosses = [...existingGlosses];
          for (const g of parsed.glosses) {
            if (g && !nextGlosses.includes(g)) nextGlosses.push(g);
          }

          // Only nouns carry a de/het article; verbs/other POS must not receive an article
          const nextPos = parsed.pos || existing.pos || null;
          const nextArticle = (nextPos && nextPos !== 'noun')
            ? null
            : (parsed.article || existing.article || null);

          updWord.run(
            nextArticle,
            nextPos,
            JSON.stringify(nextGlosses),
            JSON.stringify(themas),
            existing.id
          );
        } else {
          insWord.run(
            parsed.word,
            parsed.pos,
            parsed.article,
            JSON.stringify(parsed.glosses),
            tInfo.level,
            JSON.stringify([tInfo.slug])
          );
        }
      }
    }
  })();
}

